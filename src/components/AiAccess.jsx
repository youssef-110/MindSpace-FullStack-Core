import { useState } from "react";
import { Link, useLocation } from "react-router-dom";

export function QuotaBadge({ quota }) {
  if (!quota || quota.limit === undefined) return null;
  const low = quota.remaining <= Math.max(3, Math.round(quota.limit * 0.15));
  return (
    <div className="space-y-2" aria-live="polite">
      <p className={`text-sm ${quota.remaining === 0 || low ? "font-bold text-amber" : "text-ink-2"}`}>
        {quota.remaining === 0
          ? "You've used all of today's AI requests. They reset at midnight UTC."
          : `${quota.remaining} of ${quota.limit} AI requests left today${low ? ". Use them wisely." : "."}`}
      </p>
      {quota.globalExhausted ? (
        <p className="rounded-[var(--r-md)] bg-sunken p-3 text-sm">The AI has reached its daily limit for the whole site. It resets at midnight UTC.</p>
      ) : (
        quota.saver && (
          <p className="rounded-[var(--r-md)] bg-sunken p-3 text-sm">The AI is busy today, so answers are shorter to keep it running for everyone.</p>
        )
      )}
    </div>
  );
}

export function SignInForAi({ what = "use the AI" }) {
  const { pathname } = useLocation();
  return (
    <div className="rounded-[var(--r-md)] border border-line bg-surface p-4">
      <p className="font-bold">Sign in to {what}</p>
      <p className="mt-1 text-sm text-ink-2">Accounts are free. Each person gets a daily number of AI requests, which keeps the AI available for everyone.</p>
      <Link to={`/signin?next=${encodeURIComponent(pathname)}`} className="btn btn-primary mt-3">Sign in or create account</Link>
    </div>
  );
}

export function AiNotice({ onAccept }) {
  const [checked, setChecked] = useState(false);
  return (
    <div className="rounded-[var(--r-md)] border border-line bg-surface p-4 text-[0.95rem]">
      <p className="font-bold">Before you use the AI</p>
      <p className="mt-1 text-ink-2">
        Replies are generated by Google Gemini, so what you send (your questions, and any test scores you choose to share) goes to Google.
        Don't include your name or details that identify you. <Link to="/privacy#ai" className="link">How AI requests are handled</Link>
      </p>
      <label className="mt-3 flex items-start gap-3">
        <input type="checkbox" className="mt-1 h-5 w-5 shrink-0 accent-[var(--brand)]" checked={checked} onChange={(e) => setChecked(e.target.checked)} />
        <span>
          I explicitly consent to my questions, and any scores I choose to share, including scores that relate to mental health, being sent to
          Google to generate replies. I can stop at any time.
        </span>
      </label>
      <button className="btn btn-primary mt-3" onClick={onAccept} disabled={!checked}>Continue</button>
    </div>
  );
}
