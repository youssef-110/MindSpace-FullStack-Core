import { useState } from "react";
import { Link, useLocation } from "react-router-dom";
import { Icon } from "./ui";

const note = "flex items-start gap-2.5 rounded-[var(--r-md)] p-3.5 text-sm";

export function QuotaBadge({ quota }) {
  if (!quota || quota.limit === undefined) return null;
  const low = quota.remaining <= Math.max(3, Math.round(quota.limit * 0.15));
  return (
    <div className="space-y-2" aria-live="polite">
      {quota.remaining === 0 ? (
        <p className={`${note} bg-amber-soft font-medium text-amber`}>
          <Icon name="clock" size={18} className="mt-px" />
          You've used all of today's AI requests. They reset at midnight UTC.
        </p>
      ) : (
        <p className={`tag num max-w-full whitespace-normal leading-snug ${low ? "tag-warn" : ""}`}>
          <Icon name="spark" size={14} />
          {`${quota.remaining} of ${quota.limit} AI requests left today${low ? ". Use them wisely." : "."}`}
        </p>
      )}
      {quota.globalExhausted ? (
        <p className={`${note} bg-sunken text-ink-2`}>
          <Icon name="info" size={18} className="mt-px" />
          The AI has reached its daily limit for the whole site. It resets at midnight UTC.
        </p>
      ) : (
        quota.saver && (
          <p className={`${note} bg-sunken text-ink-2`}>
            <Icon name="info" size={18} className="mt-px" />
            The AI is busy today, so answers are shorter to keep it running for everyone.
          </p>
        )
      )}
    </div>
  );
}

export function SignInForAi({ what = "use the AI" }) {
  const { pathname } = useLocation();
  return (
    <div className="card flex flex-col gap-4 p-5 sm:flex-row sm:items-center sm:p-6">
      <span className="grid h-11 w-11 shrink-0 place-items-center rounded-full bg-brand-soft text-brand-text" aria-hidden="true">
        <Icon name="lock" size={20} />
      </span>
      <div className="flex-1">
        <p className="font-semibold text-ink">Sign in to {what}</p>
        <p className="mt-1 text-sm text-ink-3">Accounts are free. Each person gets a daily number of AI requests, which keeps the AI available for everyone.</p>
      </div>
      <Link to={`/signin?next=${encodeURIComponent(pathname)}`} className="btn btn-primary shrink-0 self-start sm:self-center">
        Sign in or create account
      </Link>
    </div>
  );
}

export function AiNotice({ onAccept }) {
  const [checked, setChecked] = useState(false);
  return (
    <div className="card p-5 text-[0.9375rem] sm:p-6">
      <p className="font-semibold text-ink">Before you use the AI</p>
      <p className="mt-1 text-ink-2">
        Replies are generated by Google Gemini, so what you send (your questions, and any test scores you choose to share) goes to Google.
        Don't include your name or details that identify you. <Link to="/privacy#ai" className="link">How AI requests are handled</Link>
      </p>
      <label className="well mt-4 flex cursor-pointer items-start gap-3 p-4 text-ink-2">
        <input type="checkbox" className="mt-0.5 h-5 w-5 shrink-0 accent-[var(--brand)]" checked={checked} onChange={(e) => setChecked(e.target.checked)} />
        <span>
          I explicitly consent to my questions, and any scores I choose to share, including scores that relate to mental health, being sent to
          Google to generate replies. I can stop at any time.
        </span>
      </label>
      <button className="btn btn-primary mt-4" onClick={onAccept} disabled={!checked}>
        Continue
      </button>
    </div>
  );
}
